const LANG_LABELS = { en: 'EN', 'zh-Hans': '简', 'zh-Hant': '繁', ja: '日' };

function detectLang() {
  const saved = localStorage.getItem('sa_lang');
  if (saved && I18N[saved]) return saved;
  const nav = navigator.language || '';
  if (/^ja/i.test(nav)) return 'ja';
  if (/^zh.*Hant/i.test(nav) || /^zh-(TW|HK|MO)/i.test(nav)) return 'zh-Hant';
  if (/^zh/i.test(nav)) return 'zh-Hans';
  return 'en';
}

